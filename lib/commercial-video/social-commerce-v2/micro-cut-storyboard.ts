export function buildMicroCutStoryboard(input: {
  scenes: SocialCommerceCurrentSceneInput[];
  offer: SocialCommerceOfferInput;
  totalDurationSeconds?: number;
}): MicroCutStoryboard {
  let cursor = 0;
  const microScenes: MicroCutScene[] = input.scenes.map((scene) => {
    const startSecond = cursor;
    const durationSeconds = scene.durationSeconds;
    const beats = buildSceneBeats(scene, startSecond, input.offer);
    cursor += durationSeconds;
    return {
      sceneId: scene.sceneId,
      macroPurpose: scene.purpose,
      startSecond: round(startSecond),
      endSecond: round(startSecond + durationSeconds),
      durationSeconds,
      beats,
      pacing: beats.length >= 3 ? "FAST_SOCIAL" : "CONTROLLED",
    };
  });

  const allBeats = microScenes.flatMap((scene) => scene.beats);
  const totalBeatDuration = allBeats.reduce((sum, item) => sum + item.durationSeconds, 0);

  return {
    version: "SOCIAL_COMMERCE_MICRO_CUT_STORYBOARD_V2",
    totalDurationSeconds: input.totalDurationSeconds ?? input.scenes.reduce((sum, scene) => sum + scene.durationSeconds, 0),
    averageBeatDurationSeconds: round(totalBeatDuration / Math.max(1, allBeats.length)),
    scenes: microScenes,
  };
}
