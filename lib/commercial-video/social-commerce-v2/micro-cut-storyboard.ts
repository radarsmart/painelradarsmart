function round(value: number): number {
  return Number(value.toFixed(2));
}

function priceText(price: number | null): string | null {
  return price === null ? null : `R$ ${price.toFixed(2).replace(".", ",")}`;
}

function beat(
  sceneId: string,
  index: number,
  startSecond: number,
  durationSeconds: number,
  data: Omit<MicroCutBeat, "beatId" | "beatIndex" | "startSecond" | "endSecond" | "durationSeconds">,
): MicroCutBeat {
  return {
    beatId: `${sceneId}-beat-${index}`,
    beatIndex: index,
    startSecond: round(startSecond),
    endSecond: round(startSecond + durationSeconds),
    durationSeconds: round(durationSeconds),
    ...data,
  };
}

